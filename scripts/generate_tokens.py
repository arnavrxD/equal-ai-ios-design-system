#!/usr/bin/env python3
"""Generates Sources/EqualDesignSystem/Tokens/*.swift from tokens/tokens.json.
Run from the repo root:  python3 scripts/generate_tokens.py"""
import json, re, os
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
T = json.load(open(os.path.join(ROOT, "tokens/tokens.json")))
OUT = os.path.join(ROOT, "Sources/EqualDesignSystem/Tokens")

def camel(name):
    parts = re.split(r"[-_.]", name)
    return parts[0] + "".join(p[:1].upper() + p[1:] for p in parts[1:])

def rgba(v):
    v = v.lstrip("#")
    if len(v) == 3: v = "".join(c * 2 for c in v)
    a = 1.0
    if len(v) == 8: a = int(v[6:8], 16) / 255; v = v[:6]
    return f"0x{v.upper()}", round(a, 3)

def esc(s): return s.replace("\\", "\\\\").replace('"', '\\"')
HEAD = "// Generated by scripts/generate_tokens.py from tokens/tokens.json. Do not edit by hand.\n\nimport SwiftUI\n\n"

# Colors
lines = [HEAD, "/// Every color token. Semantic tokens adapt to light and dark mode;\n/// primitives and the Gold palette are fixed.\npublic enum EqualColor {\n"]
for t in T["color"]["tokens"]:
    v = t["value"]
    lines.append(f"    /// {t.get('usage','')}\n")
    if isinstance(v, dict) and v.get("dark") and v["dark"] != v["light"]:
        lh, la = rgba(v["light"]); dh, da = rgba(v["dark"])
        lines.append(f"    public static let {camel(t['name'])} = Color.equalDynamic(light: {lh}, lightAlpha: {la}, dark: {dh}, darkAlpha: {da})\n\n")
    else:
        val = v if isinstance(v, str) else v["light"]
        h, a = rgba(val)
        lines.append(f"    public static let {camel(t['name'])} = Color(equalHex: {h}, alpha: {a})\n\n")
lines.append("}\n")
open(os.path.join(OUT, "EqualColor.swift"), "w").write("".join(lines))

# Spacing / radius
def lengths(fam, enum, doc):
    out = [HEAD, f"/// {doc}\npublic enum {enum} {{\n"]
    for t in T[fam]["tokens"]:
        n = camel(t["name"].split("-", 1)[1]) if "-" in t["name"] else camel(t["name"])
        if n[0].isdigit(): n = "s" + n
        out.append(f"    /// {t.get('usage','')}\n    public static let {n}: CGFloat = {float(t['value'].rstrip('px'))}\n\n")
    out.append("}\n"); open(os.path.join(OUT, enum + ".swift"), "w").write("".join(out))
lengths("spacing", "EqualSpacing", T["spacing"]["note"])
lengths("radius", "EqualRadius", T["radius"]["note"])

# Shadows
out = [HEAD, "/// Drop shadows as found in the Figma file.\npublic struct EqualShadow: Sendable {\n    public let color: Color\n    public let radius: CGFloat\n    public let x: CGFloat\n    public let y: CGFloat\n\n"]
for t in T["shadow"]["tokens"]:
    m = re.match(r"(-?[\d.]+)p?x? (-?[\d.]+)p?x? ([\d.]+)px (#[0-9a-fA-F]+)", t["value"])
    x, y, b, col = m.groups(); h, a = rgba(col)
    n = camel(t["name"].replace("shadow-", ""))
    # CSS blur radius ≈ 2 × SwiftUI shadow radius
    out.append(f"    /// {t['usage']} CSS: `{t['value']}`\n    public static let {n} = EqualShadow(color: Color(equalHex: {h}, alpha: {a}), radius: {float(b)/2}, x: {float(x)}, y: {float(y)})\n\n")
out.append("}\n\npublic extension View {\n    /// Applies an `EqualShadow` token.\n    func equalShadow(_ s: EqualShadow) -> some View {\n        shadow(color: s.color, radius: s.radius, x: s.x, y: s.y)\n    }\n}\n")
open(os.path.join(OUT, "EqualShadow.swift"), "w").write("".join(out))

# Typography
out = [HEAD, "/// The type scale: the Figma file's 22 iOS text styles in DM Sans (-2.6% tracking),\n/// plus product accents and system chrome styles.\npublic enum EqualTextStyle: String, CaseIterable, Sendable {\n"]
styles = []
for g in T["type"]["groups"]:
    for s in g["styles"]:
        styles.append((g, s)); out.append(f"    /// {s.get('usage','')}\n    case {camel(s['name'])}\n")
out.append("\n    /// Point size.\n    public var size: CGFloat {\n        switch self {\n")
for g, s in styles: out.append(f"        case .{camel(s['name'])}: return {float(s['fontSize'].rstrip('px'))}\n")
out.append("        }\n    }\n\n    /// Line height in points.\n    public var lineHeight: CGFloat {\n        switch self {\n")
for g, s in styles: out.append(f"        case .{camel(s['name'])}: return {float(s['lineHeight'].rstrip('px'))}\n")
out.append("        }\n    }\n\n    public var weight: Font.Weight {\n        switch self {\n")
W = {400: ".regular", 500: ".medium", 600: ".semibold", 700: ".bold", 800: ".heavy", 900: ".black"}
for g, s in styles: out.append(f"        case .{camel(s['name'])}: return {W[int(s['fontWeight'])]}\n")
out.append("        }\n    }\n\n    /// Tracking in em (multiply by size for points).\n    public var trackingEm: CGFloat {\n        switch self {\n")
for g, s in styles:
    ls = s.get("letterSpacing", "0em"); v = float(ls.replace("em", "")) if ls.endswith("em") else 0.0
    out.append(f"        case .{camel(s['name'])}: return {v}\n")
out.append("        }\n    }\n\n    public var isItalic: Bool { self == .typing }\n}\n")
open(os.path.join(OUT, "EqualTextStyle.swift"), "w").write("".join(out))

# Gradients (as SwiftUI gradients; hand-mapped from CSS)
print("tokens written:", len(T["color"]["tokens"]), "colors,", len(styles), "type styles")
